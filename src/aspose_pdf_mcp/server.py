"""`aspose-pdf-mcp`'s own standalone, runnable MCP server.

Auto-generated by Codegen's `generate_server_module_source` from the tracked IR — regenerate via
`run_lifecycle.py --product pdf --action rebuild` instead of patching this file directly
(rubric gate 8: hand-patched generated output is a hard-gate failure, same discipline this
package's own `tools.py` header states).

This is the real runnable entry point the public `aspose-pdf-mcp` package ships. Before
this file existed, the only actual MCP server for this product lived inside the private builder
repo's own staging area (its `generated/pdf/server.py`), which imports the builder's own
internal auth client, tool-spec builder, IR document schema, lessons store, and semantic-db
modules directly, and loaded a live `ir/pdf/*.json` snapshot at import time just to
recompute each tool's annotations and structured-output flag. None of that exists once this
package is the only thing actually published (Decision 6: every "published" release so far has
only ever been a GitLab tag of the *tools library*, `tools.py` — never a runnable server) — so
this file is a deliberate, self-contained rendering with **zero import dependency on the private
builder package**, mirroring every other file in this package's own zero-import-dependency-on-
the-builder discipline (see this package's own `_auth.py`/`_path_resolution.py` docstrings).
Every tool's annotations and
`structured_output` flag are baked into this file as literal values at the time it was
generated — never recomputed from a live IR file at server startup, since no IR file ships with
this package.

Bundles Storage's core-4 tools (FR15b) exactly like the existing staging-area servers do, so a
user connected to only this server can upload a file, operate on it, and download the result
with no second server connection.
"""

from __future__ import annotations

from typing import Any

from aspose_storage_core_mcp import (
    DeleteFileResponse,
    storage_delete_file,
    storage_download_file,
    storage_list_files,
    storage_upload_file,
)
from aspose_pdf_mcp import (
    GetDocumentPropertiesResponse,
    PutMergeDocumentsResponse,
    pdf_convert_to_doc,
    pdf_get_document_properties,
    pdf_merge_documents,
)
from aspose_pdf_mcp._auth import AsposeAuthClient
from mcp.server.mcpserver import MCPServer
from mcp_types import ToolAnnotations


server = MCPServer(
    "aspose-pdf",
    version="0.1.0",
    instructions="Real Codegen-generated MCP tools for PDF's curated operation set, plus Storage's bundled core subset (upload/download/list/delete).",
)


_auth: AsposeAuthClient | None = None


def _get_auth() -> AsposeAuthClient:
    global _auth
    if _auth is None:
        _auth = AsposeAuthClient()
    return _auth


# --- Bundled Storage core subset (FR15b) ----------------------------------------------------


def storage_upload_file_tool(filename: str, version_id: str | None = None, storage_name: str | None = None, content_base64: str | None = None, dry_run: bool = False) -> dict[str, Any]:
    # Sprint 11 real bug fix: `storage_upload_file`/`storage_delete_file` gained a `base_url`
    # parameter (Slides' v3.0 finding) inserted *before* `dry_run` in their real signatures -- a
    # positional call here would have silently passed `dry_run`'s value into `base_url` instead
    # (a real, confirmed bug, never actually exercised until now). Every storage-core call below is
    # keyword-only from this point on, immune to any future parameter reordering.
    return storage_upload_file(_get_auth(), "pdf", filename, version_id=version_id, storage_name=storage_name, content_base64=content_base64, dry_run=dry_run)


def storage_download_file_tool(filename: str, version_id: str | None = None, storage_name: str | None = None, output_filename: str | None = None, return_base64: bool = False) -> dict[str, Any]:
    return storage_download_file(_get_auth(), "pdf", filename, version_id=version_id, storage_name=storage_name, output_filename=output_filename, return_base64=return_base64)


def storage_list_files_tool(folder_name: str | None = None, storage_name: str | None = None) -> dict[str, Any]:
    return storage_list_files(_get_auth(), "pdf", folder_name=folder_name, storage_name=storage_name)


def storage_delete_file_tool(filename: str, version_id: str | None = None, storage_name: str | None = None, dry_run: bool = False) -> DeleteFileResponse:
    return storage_delete_file(_get_auth(), "pdf", filename, version_id=version_id, storage_name=storage_name, dry_run=dry_run)


_STORAGE_ANNOTATIONS = {
    "storage_upload_file": {"title": "Upload a file to Aspose Cloud Storage", "read_only_hint": False, "destructive_hint": False, "idempotent_hint": False},
    "storage_download_file": {"title": "Download a file from Aspose Cloud Storage", "read_only_hint": True, "destructive_hint": False, "idempotent_hint": True},
    "storage_list_files": {"title": "List files in an Aspose Cloud Storage folder", "read_only_hint": True, "destructive_hint": False, "idempotent_hint": True},
    "storage_delete_file": {"title": "Delete a file from Aspose Cloud Storage", "read_only_hint": False, "destructive_hint": True, "idempotent_hint": True},
}


_STORAGE_WRAPPERS = {
    "storage_upload_file": storage_upload_file_tool,
    "storage_download_file": storage_download_file_tool,
    "storage_list_files": storage_list_files_tool,
    "storage_delete_file": storage_delete_file_tool,
}

_STORAGE_REAL_FUNCS = {
    "storage_upload_file": storage_upload_file,
    "storage_download_file": storage_download_file,
    "storage_list_files": storage_list_files,
    "storage_delete_file": storage_delete_file,
}


# --- PDF's own curated tools ------------------------------------------------------------


def pdf_convert_to_doc_tool(filename: str, folder_name: str | None = None, storage_name: str | None = None, output_filename: str | None = None, return_base64: bool = False) -> dict[str, Any]:
    return pdf_convert_to_doc(_get_auth(), filename=filename, folder_name=folder_name, storage_name=storage_name, output_filename=output_filename, return_base64=return_base64)


def pdf_merge_documents_tool(filename: str, merge_request: dict[str, Any], storage_name: str | None = None, folder_name: str | None = None, dry_run: bool = False) -> PutMergeDocumentsResponse:
    return pdf_merge_documents(_get_auth(), filename=filename, merge_request=merge_request, storage_name=storage_name, folder_name=folder_name, dry_run=dry_run)


def pdf_get_document_properties_tool(filename: str, folder_name: str | None = None, storage_name: str | None = None) -> GetDocumentPropertiesResponse:
    return pdf_get_document_properties(_get_auth(), filename=filename, folder_name=folder_name, storage_name=storage_name)


_PRODUCT_ANNOTATIONS = {
    "pdf_convert_to_doc": {"title": 'Convert a Cloud-stored PDF document to DOC format', "read_only_hint": True, "destructive_hint": False, "idempotent_hint": True, "open_world_hint": True, "structured_output": True},
    "pdf_merge_documents": {"title": 'Merge a list of Cloud-stored PDF documents into one', "read_only_hint": False, "destructive_hint": False, "idempotent_hint": False, "open_world_hint": True, "structured_output": True},
    "pdf_get_document_properties": {"title": "Get a Cloud-stored PDF document's properties", "read_only_hint": True, "destructive_hint": False, "idempotent_hint": True, "open_world_hint": True, "structured_output": True},
}


_PRODUCT_WRAPPERS = {
    "pdf_convert_to_doc": pdf_convert_to_doc_tool,
    "pdf_merge_documents": pdf_merge_documents_tool,
    "pdf_get_document_properties": pdf_get_document_properties_tool,
}


_PRODUCT_REAL_FUNCS = {
    "pdf_convert_to_doc": pdf_convert_to_doc,
    "pdf_merge_documents": pdf_merge_documents,
    "pdf_get_document_properties": pdf_get_document_properties,
}


def _register_all_tools() -> None:
    # Storage core subset first (FR15b) — same 4 tools, same annotations, every rendered
    # server bundles.
    for name, wrapper in _STORAGE_WRAPPERS.items():
        annotations = _STORAGE_ANNOTATIONS[name]
        real_description = _STORAGE_REAL_FUNCS[name].__doc__
        server.add_tool(
            wrapper,
            name=name,
            title=annotations["title"],
            description=real_description or annotations["title"],
            annotations=ToolAnnotations(
                title=annotations["title"],
                read_only_hint=annotations["read_only_hint"],
                destructive_hint=annotations["destructive_hint"],
                idempotent_hint=annotations["idempotent_hint"],
                open_world_hint=True,
            ),
            structured_output=True,
        )

    # PDF's own curated tools.
    for name, wrapper in _PRODUCT_WRAPPERS.items():
        annotations = _PRODUCT_ANNOTATIONS[name]
        real_description = _PRODUCT_REAL_FUNCS[name].__doc__
        server.add_tool(
            wrapper,
            name=name,
            title=annotations["title"],
            description=real_description or annotations["title"],
            annotations=ToolAnnotations(
                title=annotations["title"],
                read_only_hint=annotations["read_only_hint"],
                destructive_hint=annotations["destructive_hint"],
                idempotent_hint=annotations["idempotent_hint"],
                open_world_hint=annotations["open_world_hint"],
            ),
            structured_output=annotations["structured_output"],
        )


_register_all_tools()


def main() -> None:
    server.run(transport="stdio")


if __name__ == "__main__":
    main()
